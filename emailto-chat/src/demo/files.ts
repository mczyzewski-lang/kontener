/**
 * Generates real, openable sample files for Demo Mode (no network, no binaries in the repo).
 */

function toAscii(s: string): string {
  const map: Record<string, string> = { ą: "a", ć: "c", ę: "e", ł: "l", ń: "n", ó: "o", ś: "s", ź: "z", ż: "z", Ą: "A", Ć: "C", Ę: "E", Ł: "L", Ń: "N", Ó: "O", Ś: "S", Ź: "Z", Ż: "Z", "—": "-", "–": "-", "’": "'", "“": '"', "”": '"', "…": "...", "€": "EUR" };
  return s.replace(/[^\x20-\x7e]/g, (c) => map[c] ?? "");
}

function pdfEscape(s: string): string {
  return toAscii(s).replace(/([\\()])/g, "\\$1");
}

function b64(s: string): string {
  if (typeof btoa === "function") return btoa(s);
  return Buffer.from(s, "binary").toString("base64");
}

/** A tiny, valid single-page PDF with a title and some lines of text. */
export function makePdf(title: string, lines: string[]): { dataUrl: string; size: number } {
  const content = [
    "BT",
    "/F2 22 Tf",
    "72 770 Td",
    `(${pdfEscape(title)}) Tj`,
    "/F1 11 Tf",
    "0 -34 Td",
    "16 TL",
    ...lines.map((l) => `(${pdfEscape(l)}) '`),
    "0 -40 Td",
    "/F1 8 Tf",
    "(Sample document generated by emailto.chat Demo Mode) Tj",
    "ET",
    "0.14 0.39 0.92 rg",
    "72 790 60 4 re f",
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return { dataUrl: `data:application/pdf;base64,${b64(pdf)}`, size: pdf.length };
}

export function makeText(text: string, mime = "text/plain"): { dataUrl: string; size: number } {
  const bytes = new TextEncoder().encode(text);
  let bin = "";
  bytes.forEach((b) => (bin += String.fromCharCode(b)));
  return { dataUrl: `data:${mime};charset=utf-8;base64,${b64(bin)}`, size: bytes.length };
}

const imageCache = new Map<string, string>();

/**
 * A pleasant abstract "photo" rendered with <canvas> (JPEG). Browser only;
 * falls back to an SVG data URL when canvas is unavailable.
 */
export function makeImage(seed: number, label: string, hues: [number, number]): string {
  const key = `${seed}:${label}`;
  const cached = imageCache.get(key);
  if (cached) return cached;
  let url: string;
  if (typeof document !== "undefined") {
    const c = document.createElement("canvas");
    c.width = 1200;
    c.height = 800;
    const ctx = c.getContext("2d");
    if (ctx) {
      const g = ctx.createLinearGradient(0, 0, 1200, 800);
      g.addColorStop(0, `hsl(${hues[0]} 70% 62%)`);
      g.addColorStop(1, `hsl(${hues[1]} 65% 42%)`);
      ctx.fillStyle = g;
      ctx.fillRect(0, 0, 1200, 800);
      let s = seed * 9301 + 49297;
      const rnd = () => ((s = (s * 9301 + 49297) % 233280) / 233280);
      for (let i = 0; i < 14; i++) {
        ctx.beginPath();
        ctx.fillStyle = `hsla(${hues[i % 2]} 80% ${55 + rnd() * 35}% / ${0.12 + rnd() * 0.25})`;
        ctx.arc(rnd() * 1200, rnd() * 800, 60 + rnd() * 260, 0, Math.PI * 2);
        ctx.fill();
      }
      ctx.fillStyle = "rgba(255,255,255,0.92)";
      ctx.font = "600 44px system-ui, sans-serif";
      ctx.fillText(label, 60, 730);
      url = c.toDataURL("image/jpeg", 0.85);
    } else url = svgFallback(label, hues);
  } else url = svgFallback(label, hues);
  imageCache.set(key, url);
  return url;
}

function svgFallback(label: string, hues: [number, number]): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(${hues[0]},70%,62%)"/><stop offset="1" stop-color="hsl(${hues[1]},65%,42%)"/></linearGradient></defs><rect width="1200" height="800" fill="url(#g)"/><text x="60" y="730" font-family="system-ui" font-size="44" fill="white">${label.replace(/[<&>]/g, "")}</text></svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}
